#!/usr/bin/env node
// The navigation as it ships (#49 scope item 2). `resolveNav`, `resolveFooter` and `resolveUtility` (src/data/nav.ts) drop every link whose
// route is not live, so the nav a visitor gets is the nav data filtered by the live route set. This module computes that, from disk and
// with the build's own route logic, and `--write` records it as the `shipped` block of tests/unit/foundation/fixtures/nav-snapshot.json.
// The snapshot test (tests/unit/wp-99/nav-final.test.ts) then fails when a route is added, cut or renamed without regenerating it, and
// when a link in the shipped nav does not resolve.
// Usage: node scripts/lib/wave8/nav-final.mjs [--root .] [--write]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { routeContextFromDisk } from '../../../src/data/cta/live.ts';
import { applyButton, resolveFooter, resolveNav, resolveUtility } from '../../../src/data/nav.ts';
import { computeRouteState } from '../../../src/lib/route-core.ts';

export const SNAPSHOT = 'tests/unit/foundation/fixtures/nav-snapshot.json';

const NOTE =
  'Generated by scripts/lib/wave8/nav-final.mjs --write (WP-99, #49): the navigation resolved against the live route set of the tree, that is the nav a visitor gets. ' +
  'Regenerate with `node scripts/lib/wave8/nav-final.mjs --write` when a route is added, cut or renamed; tests/unit/wp-99/nav-final.test.ts fails until you do.';

/**
 * The shipped navigation of the repository at `root`.
 * @returns {{ note: string, apply: string, utility: string[], sections: { id: string, kind: string, href: string, columns: { heading: string, links: string[] }[], strip: string[] }[], footer: { heading: string, links: string[] }[] }}
 */
export function shippedNav(root = process.cwd()) {
  const state = computeRouteState(routeContextFromDisk(root));
  const isLive = (href) => state.isLive(href);
  return {
    note: NOTE,
    apply: applyButton.href,
    utility: resolveUtility(isLive).map((l) => l.href),
    sections: resolveNav(isLive).map((item) =>
      item.kind === 'direct'
        ? { id: item.id, kind: 'direct', href: item.href, columns: [], strip: [] }
        : { id: item.id, kind: 'mega', href: item.href, columns: item.columns.map((c) => ({ heading: c.heading, links: c.links.map((l) => l.href) })), strip: item.strip.map((l) => l.href) },
    ),
    footer: resolveFooter(isLive).map((c) => ({ heading: c.heading, links: c.links.map((l) => l.href) })),
  };
}

/** Every href the shipped nav renders, once, for link-resolution checks. */
export function shippedHrefs(nav) {
  return [...new Set([nav.apply, ...nav.utility, ...nav.sections.flatMap((s) => [s.href, ...s.columns.flatMap((c) => c.links), ...s.strip]), ...nav.footer.flatMap((c) => c.links)])];
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const argv = process.argv.slice(2);
  const root = argv.includes('--root') ? argv[argv.indexOf('--root') + 1] : process.cwd();
  const nav = shippedNav(root);
  if (argv.includes('--write')) {
    const file = join(root, SNAPSHOT);
    const snapshot = JSON.parse(readFileSync(file, 'utf8'));
    writeFileSync(file, `${JSON.stringify({ ...snapshot, shipped: nav }, null, 1)}\n`);
    console.log(`nav-final: wrote the shipped block of ${SNAPSHOT} (${nav.sections.length} sections, ${shippedHrefs(nav).length} distinct links)`);
  } else {
    console.log(JSON.stringify(nav, null, 1));
  }
}
